import fs from 'node:fs/promises';
import { parseEnv } from 'node:util';
import { join } from 'node:path';
import { readAmazonJson } from '../services/amazonDataSecurity.mjs';
import { readJson, monitorRoot } from '../services/amazonMonitorStore.mjs';
import { previousSalesProfitStock, salesProfitFinanceForRange } from '../services/salesProfitHistory.mjs';
import { resolveSalesProfitStock } from '../services/salesProfitStock.mjs';
import { liveSalesProfit } from '../services/liveSalesProfit.mjs';
import { salesProfitWorkbook, writeSalesProfitWorkbook } from '../services/salesProfitWorkbook.mjs';
for(const [key,value] of Object.entries(parseEnv(await fs.readFile('.env','utf8').catch(()=>''))))if(process.env[key]==null)process.env[key]=value;
const params=new URLSearchParams({startDate:process.argv[2],endDate:process.argv[3]});
const destination=process.argv[4];
const report=await readAmazonJson(join(process.cwd(),'outputs','amazon-cdc','sales-profit-test-orders.json'));
const finance=await salesProfitFinanceForRange(params);
const latest=await readJson(join(monitorRoot(),'latest.json'));
const catalog=latest?await readJson(join(monitorRoot(),'runs',latest.id+'.json')):null;
const inventory=await readAmazonJson(join(process.cwd(),'outputs','amazon-cdc','inventory.json'));
const previousSnapshot=await previousSalesProfitStock(params);
const history=await readJson(join(monitorRoot(),'sales-profit-inventory-history.json'));
const stock=resolveSalesProfitStock(catalog,inventory);
const data=liveSalesProfit(report,finance,stock?{...stock,previousSnapshot,history}:null,params);
await fs.writeFile(destination,writeSalesProfitWorkbook(salesProfitWorkbook(data)),{mode:0o600});
