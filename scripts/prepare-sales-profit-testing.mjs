import fs from 'node:fs/promises';
import { parseEnv } from 'node:util';
import { join } from 'node:path';
import { readAmazonJson } from '../services/amazonDataSecurity.mjs';
import { readJson, atomicJson, monitorRoot } from '../services/amazonMonitorStore.mjs';
import { salesProfitTestingRange } from '../services/salesProfitTestingRange.mjs';
for(const [key,value] of Object.entries(parseEnv(await fs.readFile('.env','utf8'))))if(process.env[key]==null)process.env[key]=value;
const range=salesProfitTestingRange();
const report=await readAmazonJson(join(process.cwd(),'outputs','amazon-cdc','order-report.json'));
const within=value=>String(value||'').slice(0,10)>=range.startDate&&String(value||'').slice(0,10)<=range.endDate;
const rows=report.rows.filter(row=>within(row['purchase-date']));
await atomicJson(join(process.cwd(),'outputs','amazon-cdc','sales-profit-test-orders.json'),{...report,rows,coverageStart:range.startDate,coverageEnd:range.endDate});
const history=await readJson(join(monitorRoot(),'sales-profit-finances-history.json'));
const finance=history&&String(history.start).slice(0,10)<=range.startDate?history:await readJson(join(monitorRoot(),'sales-profit-finances.json'));
if(!finance||String(finance.start).slice(0,10)>range.startDate||String(finance.end).slice(0,10)<range.endDate)throw Error('Finance coverage does not include the testing window.');
const transactions=(finance?.transactions||[]).filter(event=>within(event.postedDate));
const rawEvents=finance?.rawEvents?.filter(({event})=>within(event.PostedDate));
if(finance)await atomicJson(join(monitorRoot(),'sales-profit-test-finances.json'),{...finance,start:range.startDate,transactions,...(rawEvents?{rawEvents}:{} )});
console.log(JSON.stringify({range,orders:rows.length,financialEvents:transactions.length}));
